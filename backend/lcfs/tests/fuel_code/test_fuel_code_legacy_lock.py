"""Database-backed tests for which fuel codes the legacy IDIR fuel code pages
can still process (#5308).

The CI application workflow now takes pathways through to approved fuel codes.
The legacy pages keep approved fuel codes, and the drafts they started
themselves (a new code from scratch, or an approved code reopened with Edit).
A code generated by a CI application belongs to that application until it is
completed, and any other code that isn't approved is locked.
"""

